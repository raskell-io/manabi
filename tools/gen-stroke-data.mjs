#!/usr/bin/env node
/**
 * Bundles stroke-order data (for the Hanzi Writer drawing pad) for every
 * hanzi/kanji on the Scripts page, in the seed, and in the radical table (plus
 * the Traditional forms of the Chinese ones, via opencc-js), so
 * stroke order and tracing work offline. Run manually (needs network):
 *
 *   node tools/gen-stroke-data.mjs
 *
 * Writes static/strokes/{zh,ja}/<codepoint-hex>.json and src/lib/strokes-index.ts
 * (which characters are bundled). Anything else is fetched from the same pinned
 * CDN packages at runtime (src/lib/strokes.ts).
 *
 * Data (see static/strokes/README.md for licenses):
 *  - zh: hanzi-writer-data (Make Me a Hanzi; Arphic Public License)
 *  - ja: hanzi-writer-data-jp (animCJK, Japanese glyph forms; Arphic Public License / LGPL)
 */
import { build } from 'esbuild';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

// Keep in sync with STROKE_CDN in src/lib/strokes.ts.
const CDN = {
	zh: 'https://cdn.jsdelivr.net/npm/hanzi-writer-data@2.0.1',
	ja: 'https://cdn.jsdelivr.net/npm/hanzi-writer-data-jp@0.0.1'
};
const HAN = /\p{Script=Han}/u;

async function loadTs(entry) {
	const out = join(tmpdir(), `manabi-${Date.now()}-${Math.random().toString(36).slice(2)}.mjs`);
	await build({ entryPoints: [entry], bundle: true, format: 'esm', platform: 'node', outfile: out, logLevel: 'silent' });
	const mod = await import(pathToFileURL(out).href);
	rmSync(out, { force: true });
	return mod;
}

const sd = await loadTs('src/lib/scripts-data.ts');
const { seedItems } = await loadTs('src/lib/db/seed.ts');
const { RADICALS } = await loadTs('src/lib/radicals-data.ts');

const want = { zh: new Set(), ja: new Set() };
const add = (lang, text) => {
	for (const c of text ?? '') if (HAN.test(c)) want[lang].add(c);
};
// Chinese also bundles the Traditional forms (Taiwan + Hong Kong) the script option shows.
const OpenCC = await import('opencc-js/cn2t');
const toTraditional = ['tw', 'hk'].map((to) => OpenCC.Converter({ from: 'cn', to }));
const addZh = (text) => {
	add('zh', text);
	for (const conv of toTraditional) add('zh', conv(text ?? ''));
};
for (const g of [...sd.HANZI_HSK1, ...sd.HANZI_HSK2, ...sd.HANZI_HSK3]) addZh(g.char);
for (const g of [...sd.KANJI_N5, ...sd.KANJI_N4, ...sd.KANJI_N3]) add('ja', g.char);
for (const it of seedItems()) if (it.language === 'zh') addZh(it.target); else if (it.language === 'ja') add('ja', it.target);
for (const r of RADICALS) for (const lang of ['zh', 'ja']) add(lang, r.char + r.variants.join(''));

async function fetchOne(lang, c) {
	for (let attempt = 0; attempt < 3; attempt++) {
		try {
			const r = await fetch(`${CDN[lang]}/${encodeURIComponent(c)}.json`, { signal: AbortSignal.timeout(15000) });
			if (r.status === 404) return null;
			if (!r.ok) throw new Error(String(r.status));
			const json = await r.json();
			return json.strokes?.length ? json : null;
		} catch {
			await new Promise((res) => setTimeout(res, 500 * (attempt + 1)));
		}
	}
	return null;
}

const index = {};
for (const lang of ['zh', 'ja']) {
	const dir = `static/strokes/${lang}`;
	mkdirSync(dir, { recursive: true });
	const file = (c) => `${dir}/${c.codePointAt(0).toString(16)}.json`;
	const chars = [...want[lang]].sort();
	// Drop files no longer wanted; keep (don't re-download) the rest.
	const keep = new Set(chars.map((c) => file(c).split('/').pop()));
	for (const f of readdirSync(dir)) if (!keep.has(f)) rmSync(`${dir}/${f}`);
	const got = chars.filter((c) => existsSync(file(c)) && JSON.parse(readFileSync(file(c), 'utf8')).strokes?.length);
	const todo = chars.filter((c) => !got.includes(c));
	for (let i = 0; i < todo.length; i += 16) {
		const batch = todo.slice(i, i + 16);
		const res = await Promise.all(batch.map((c) => fetchOne(lang, c)));
		batch.forEach((c, j) => {
			if (!res[j]) return;
			writeFileSync(file(c), JSON.stringify(res[j]));
			got.push(c);
		});
	}
	got.sort();
	index[lang] = got.join('');
	console.log(`${lang}: ${got.length}/${chars.length} characters bundled`);
}

writeFileSync(
	'src/lib/strokes-index.ts',
	`// AUTO-GENERATED by tools/gen-stroke-data.mjs — do not edit by hand.
// Characters whose stroke data ships in static/strokes/{zh,ja}/ (works offline).
/* prettier-ignore */
export const BUNDLED_STROKES: Record<'zh' | 'ja', string> = ${JSON.stringify(index)};
`
);
