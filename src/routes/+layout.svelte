			<span class="streak" class:lit={streak.today} title="{streak.days}-day streak">
				<Flame size={18} />{streak.days}
			</span>
			<a href="/settings" class="icon-btn" class:active={settingsActive} aria-label="Settings">
				<SettingsIcon size={20} />
			</a>
		</header>

		<div class="shell">
			<!-- Desktop sidebar -->
			<aside class="sidebar">
