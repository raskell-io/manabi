<script lang="ts">
	import '../app.css';
	import { onMount } from 'svelte';
	import { get } from 'svelte/store';
	import { page } from '$app/stores';
	import { Settings as SettingsIcon, Sun, Moon, Download, Flame } from 'lucide-svelte';
	import Mascot from '$lib/components/Mascot.svelte';
	import InstallHint from '$lib/components/InstallHint.svelte';
	import { armInstallCapture, installPrompt, promptInstall } from '$lib/install';
	import { allItems, initDB, practiceTimes, settings, updateSettings } from '$lib/db/store';
	import { setZhReadingMode, setZhRuby, setZhScript, setZhVariants } from '$lib/chinese';
	import { computeStreak } from '$lib/today';
	import { LANGUAGES } from '$lib/db/types';
	import { startAutoSync } from '$lib/sync';
	import { isNavActive, LIBRARY, PRIMARY } from '$lib/nav';
	import { immersive } from '$lib/ui';

	let { children } = $props();
	let ready = $state(false);

	const THEME_COLOR = { light: '#ffffff', dark: '#13111f' } as const;
	function applyTheme(theme: string) {
		const root = document.documentElement;
		root.classList.remove('light', 'dark');
		if (theme === 'light' || theme === 'dark') root.classList.add(theme);
		// The status-bar tint (PWA / mobile chrome) must follow a forced theme, not
		// just the system scheme the two <meta theme-color> tags are keyed on.
		document.querySelectorAll<HTMLMetaElement>('meta[name="theme-color"]').forEach((m) => {
			const own = m.media.includes('dark') ? 'dark' : 'light';
			m.content = theme === 'light' || theme === 'dark' ? THEME_COLOR[theme] : THEME_COLOR[own];
		});
	}
	$effect(() => {
		if (ready) applyTheme($settings.theme);
	});
	// Chinese display script (Simplified / Traditional); the first load is awaited in onMount.
	$effect(() => {
		if (ready) void setZhScript($settings.zhScript);
	});
	$effect(() => setZhReadingMode($settings.zhReading));
	$effect(() => setZhRuby($settings.zhRuby));
	$effect(() => setZhVariants($allItems));

	function prefersDark(): boolean {
		return typeof window !== 'undefined' && window.matchMedia('(prefers-color-scheme: dark)').matches;
	}
	const isDark = $derived($settings.theme === 'dark' || ($settings.theme === 'system' && prefersDark()));
	function toggleTheme() {
		updateSettings({ theme: isDark ? 'light' : 'dark' });
	}

	const activePath = $derived($page.url.pathname);
	const langNative = $derived(LANGUAGES.find((l) => l.code === $settings.activeLanguage)?.native ?? '');
	const sidebarPrimary = PRIMARY.filter((p) => p.href !== '/library');
	const settingsActive = $derived(isNavActive({ href: '/settings' }, activePath));
	const streak = $derived(computeStreak($practiceTimes));

	onMount(async () => {
		await initDB();
		// Load the Traditional converter before the first render, so a Traditional
		// reader never sees a flash of Simplified.
		await setZhScript(get(settings).zhScript);
		ready = true;
		armInstallCapture();
		// GitHub sync (if configured): pull/merge/push on start + when back online.
		void startAutoSync();
		// Register the precaching service worker (generated by @vite-pwa). This
		// makes the app installable + the shell available offline. Fire-and-forget
		// so it never blocks boot; the SW self-updates (registerType autoUpdate).
		if ('serviceWorker' in navigator) {
			navigator.serviceWorker.register('/sw.js', { scope: '/' }).catch(() => {});
		}
	});
</script>

{#if !ready}
	<div class="boot">
		<Mascot size={110} mood="happy" />
		<span class="wordmark">manabi</span>
	</div>
{:else}
